func shardKind(lower string, serial bool, steps int) *kindData {
	e2e := &e2eData{Serial: serial}
	for i := 0; i < steps; i++ {
		e2e.StepJSON = append(e2e.StepJSON, []string{"`{}`"})
		e2e.Steps = append(e2e.Steps, []sweepCopy{{}})
	}
	return &kindData{Kind: strings.ToUpper(lower[:1]) + lower[1:], Lower: lower, E2E: e2e}
}

// Every step runs in exactly one shard, and the last shard takes what no label names.
func TestShardsRunEveryStepOnce(t *testing.T) {
	kinds := []*kindData{shardKind("alpha", false, 6), shardKind("beta", true, 3), shardKind("gamma", true, 2), shardKind("delta", false, 0)}
	shards := packShards(kinds)
	if shards[len(shards)-1].Name != restShard {
		t.Fatalf("the last shard must be %s: %+v", restShard, shards)
	}
	for _, kind := range kinds[:3] {
		for i := range kind.E2E.Steps {
			label := coverageLabel(kind, i+1)
			n := 0
			for _, s := range shards[:len(shards)-1] {
				if strings.Contains(s.Filter, label+" ") || strings.Contains(s.Filter, label+")") {
					n++
				}
			}
			if n != 1 {
				t.Errorf("%s runs in %d shards, want 1: %+v", label, n, shards)
			}
			if rest := shards[len(shards)-1].Filter; !strings.Contains(rest, label) {
				t.Errorf("the rest shard must exclude %s: %s", label, rest)
			}
		}
	}
	for _, s := range shards[:len(shards)-1] {
		if s.Steps > shardMinutes/minutesPerStep && s.Steps != 3 {
			t.Errorf("shard %s holds %d steps, over the limit: %+v", s.Name, s.Steps, shards)
		}
	}
}

// The steps of a Serial kind stay together, because Ginkgo Serial holds only inside one run.
func TestShardsKeepASerialKindInOneShard(t *testing.T) {
	shards := packShards([]*kindData{shardKind("alpha", false, 5), shardKind("beta", true, 3)})
	var holding []string
	for _, s := range shards[:len(shards)-1] {
		if strings.Contains(s.Filter, "coverage-beta-1") {
			holding = append(holding, s.Name)
			for _, label := range []string{"coverage-beta-2", "coverage-beta-3"} {
				if !strings.Contains(s.Filter, label) {
					t.Errorf("%s must stay with coverage-beta-1: %s", label, s.Filter)
				}
			}
		}
	}
	if len(holding) != 1 {
		t.Fatalf("a Serial kind must be in one shard: %v", holding)
	}
}

func TestShardsGiveALargeSerialKindItsOwnShard(t *testing.T) {
	shards := packShards([]*kindData{shardKind("big", true, shardMinutes+2), shardKind("small", false, 1)})
	if len(shards) != 3 {
		t.Fatalf("want a shard for the big kind, one for the small one, and the rest: %+v", shards)
	}
}

func TestShardsWithNoStepsHaveOnlyTheRestShard(t *testing.T) {
	shards := packShards([]*kindData{shardKind("none", false, 0)})
	if len(shards) != 1 || shards[0].Filter != "coverage" {
		t.Fatalf("got %+v", shards)
	}
}

func TestShardFileHasTheGeneratorHeader(t *testing.T) {
	data, err := renderShards([]*kindData{shardKind("alpha", false, 1)})
	if err != nil {
		t.Fatal(err)
	}
	line, _, _ := strings.Cut(string(data), "\n")
	if !strings.HasPrefix(line, "# Code generated by") || !ownedData(data) {
		t.Errorf("the generator must own the shard file: %q", line)
	}
	if !strings.Contains(string(data), "&&") {
		t.Error("the filter must keep its && characters: the JSON must not escape them")
	}
}
